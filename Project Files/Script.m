% Generated by MATLAB(R) 24.1 and Signal Processing Toolbox 24.1.
% Generated on: 14-Dec-2024 19:40:38

% Butterworth Lowpass filter designed using FDESIGN.LOWPASS.

% All frequency values are in Hz.
Fs = 44100;  % Sampling Frequency
N  = 10;   % Order
Fc = 5000;  % Cutoff Frequency

% Construct an FDESIGN object and call its BUTTER method.
h  = fdesign.lowpass('N,F3dB', N, Fc, Fs);
Hd = design(h, 'butter');
end
%% Define BandpassFilter
function Hd = BandpassFilter
%BANDPASSFILTER Returns a discrete-time filter object.

% MATLAB Code
% Generated by MATLAB(R) 24.1 and Signal Processing Toolbox 24.1.
% Generated on: 16-Dec-2024 16:14:07
% Butterworth Bandpass filter designed using FDESIGN.BANDPASS.
% All frequency values are in Hz.
Fs = 44100;  % Sampling Frequency
N   = 4;     % Order
Fc1 = 3500;  % First Cutoff Frequency
Fc2 = 5000;  % Second Cutoff Frequency

% Construct an FDESIGN object and call its BUTTER method.
h  = fdesign.bandpass('N,F3dB1,F3dB2', N, Fc1, Fc2, Fs);
Hd = design(h, 'butter');
end

%% Applying low-pass filter
filtered = filter(Lowpass3,Y);

%% Applying bandpass filter
bp_filter = BandpassFilter; % Call the bandpass filter function
filtered_bp = filter(bp_filter, filtered); % Apply the bandpass filter

%% Convert the filtered signal to audio file
audiowrite('Filtered.wav', filtered_bp, fs);

%% Play the filtered audio
player = audioplayer(filtered_bp, fs);
play(player);

%% Fast Fourier Transform Comparison between the original and the filtered audio
figure,
subplot(2, 1, 1);
plot(Ylength, abs(YFFT));
title('Fast Fourier Transform for the Original audio');
xlabel('Frequency (Hz)');
ylabel('Amplitude (db)');
grid;
filteredFFT = fft(filtered_bp);
filtered_length = length(filteredFFT);
filtered_length = (0:filtered_length-1)/filtered_length * fs;
subplot(2, 1, 2);
plot(filtered_length, abs(filteredFFT));
title('Fast Fourier Transform for the Filtered audio');
xlabel('Frequency (Hz)');
ylabel('Amplitude (db)');
grid;

%% Spectrogram Comparison between the original and the filtered audio
subplot(2,2,1);
spectrogram(Y,'yaxis') %% Sequence (n)
title('Spectrogram of the original audio signal in Sequence (n) ')
subplot(2,2,3)
spectrogram(Y,[],[],[],fs,'yaxis') %% Time (s)
title('Spectrogram of the original audio signal in Time (s) ')
subplot(2,2,2);
spectrogram(filtered_bp,'yaxis') %% Sequence (n)
title('Spectrogram of the filtered audio signal in Sequence (n) ')
subplot(2,2,4)
spectrogram(filtered_bp,[],[],[],fs,'yaxis') %% Time (s)
title('Spectrogram of the filtered audio signal in Time (s) ')

%% Power Spectrum Density Comparison Power spectrum density between the original and the filtered audio
figure,
subplot(2,2,1); %% sequence (n)
pwelch(Y)
subplot(2,2,3)
pwelch(Y,[],[],[],fs)%% Time (s)
subplot(2,2,2); %% sequence (n)
pwelch(filtered_bp)
subplot(2,2,4)
pwelch(filtered_bp,[],[],[],fs)%% Time (s)

%% Comparison between the original and the filtered audio signal
figure;
subplot(2,1,1)
plot(Y,'linewidth',1.5);
xlabel('samples');
ylabel('Amplitude');
title('Graph of the original audio signal');
grid on
subplot(2,1,2)
plot(filtered_bp,'linewidth',1.5);
xlabel('samples');
ylabel('Amplitude');
title('Graph of the filtered audio signal');
grid on

%% Low Pass Filter LPF (Z-Plane, Impulse Response, Frequency Response)
section1_numerator_LPF =0.110315*[1,2,1];
section1_denominator_LPF = [1,-1.373,0.8144];
%section 2 of filter
section2_numerator_LPF = 0.093769*[1,2,1];
section2_denominartor_LPF = [1,-1.1672,0.5423];
%section 3 of filter
section3_numerator_LPF = 0.083159*[1,2,1];
section3_denominrator_LPF = [1,-1.03517,0.3678];
%section 4 of filter
section4_numerator_LPF = 0.0768427*[1,2,1];
section4_denominrator_LPF = [1,-0.9565,0.2639];
%section 5 of filter
section5_numerator_LPF = 0.07389*[1,2,1];
section5_denominrator_LPF = [1,-0.9198,0.2153];
%computing b and a of filter transfer function
section_numerator_LPF = conv(conv(conv(section1_numerator_LPF,section2_numerator_LPF),conv(section3_numerator_LPF,section4_numerator_LPF)),section5_numerator_LPF);
section_denominrator_LPF =conv(conv(conv(section1_denominator_LPF,section2_denominartor_LPF),conv(section3_denominrator_LPF,section4_denominrator_LPF)),section5_denominrator_LPF);
b_lowpass = section_numerator_LPF;
a_lowpass = section_denominrator_LPF;
%pole zero plot of the filter
figure,
zplane(b_lowpass,a_lowpass);
grid;
title('Low Pass Filter Z-Plane')
%impulse response of the filter
figure,
impz(b_lowpass,a_lowpass);
grid;
fs=44100;
title('Low Pass Filter Impulse Response')
%frequency response of the designed filter
figure,
freqz(b_lowpass,a_lowpass,1024,fs); %% Frequency response (Hz)
grid on;
title('Low Pass Filter Frequency Response')
%% Band Pass Filter (Z-Plane, Impulse Response, Frequency Response)
section1_numerator_BPF = 0.099456*[1,0,-1];
section1_denominator_BPF = [1,-1.4373755,0.8453319];
%section 2 of filter
section2_numerator_BPF = 0.099456*[1,0,-1];
section2_denominator_BPF = [1,-1.62191,0.874419];
%computing b and a of filter transfer function
section_numerator_BPF = conv(section1_numerator_BPF,section2_numerator_BPF);
section_denominator_BPF = conv(section1_denominator_BPF,section2_denominator_BPF);
b_bandpass = section_numerator_BPF;
a_bandpass = section_denominator_BPF;
%pole zero plot of the filter
figure,
zplane(b_bandpass,a_bandpass);
grid;
title('Band Pass Filter Z-Plane')
%impulse response of the filter
figure,
impz(b_bandpass,a_bandpass);
grid;
fs=44100;
title('Band Pass Filter Impulse Response')
%frequency response of the designed filter
figure,
freqz(b_bandpass,a_bandpass,1024,fs); %% Frequency response (Hz)
grid on;
title('Band Pass Filter Frequency Response')
