% To have a clean working space
close all; % To close all opened figures
clear all; % To clear all the variables
clc; % To clear the Command Window

%% To export the audio file and read it
[Y,fs]=audioread('Original.mp3');
Y = sum(Y,2)/size(Y,2); % Convert Stereo to Mono channel

%% To plot the converted Signal
figure,
plot(Y,'linewidth',1.5)
xlabel('samples');
ylabel('Amplitude');
title('Graph of the original audio signal');
grid on

%% Convert Y signal back to an audio file
audiowrite('Filtered.wav',Y,fs)

%% Play audio file in MATLAB
player = audioplayer(Y,fs);
play(player);

%% Spectrogram
subplot(2,1,1)
spectrogram(Y,'yaxis') %% Sequence (n)
title('Spectrogram of the original audio signal in Sequence (n) ')
subplot(2,1,2)
spectrogram(Y,[],[],[],fs,'yaxis') %% Time (s)
title('Spectrogram of the original audio signal in Time (s) ')

%% Power spectrum density
figure,
subplot(2,1,1); %% sequence (n)
pwelch(Y)
subplot(2,1,2)
pwelch(Y,[],[],[],fs)%% Time (s)

%% FFT for original audio
YFFT= fft(Y); %Find FT using FFT function
Ylength=length(YFFT);
Ylength= (0:Ylength-1)/Ylength*fs;
figure,
plot(Ylength,abs(YFFT));
title('Fast Fourier Transform for the Original audio');
xlabel('Frequency (Hz)');
ylabel('Amplitude (db)');
grid on

%% Define   Lowpass3
function Hd = Lowpass3
